# setup.ps1 — one-time bootstrap of the portable Jarvis on a new PC.
# Run: powershell -ExecutionPolicy Bypass -File setup.ps1
param(
    [switch]$SkipCompanionDeps   # skip pip install for the chat companion
)
$ErrorActionPreference = "Continue"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$Bridge = Join-Path $Root "DevinBridge"
$Config = Join-Path $Bridge "bridge_config.json"

Write-Host "== Jarvis portable setup ==" -ForegroundColor Cyan
Write-Host "Install root: $Root"

# --- 1. Python -----------------------------------------------------------
$py = $null
foreach ($cand in @("py -3", "python")) {
    try {
        $v = & cmd /c "$cand --version 2>&1"
        if ($v -match "Python 3\.(1[0-9]|[0-9])") { $py = $cand; break }
    } catch {}
}
if (-not $py) {
    Write-Host "ERROR: Python 3.10+ not found. Install from python.org first." -ForegroundColor Red
    exit 1
}
Write-Host "Python: $py ($( & cmd /c "$py --version" ))"

# --- 2. bridge_config.json placeholders ----------------------------------
$cfg = Get-Content $Config -Raw
$cfg = $cfg.Replace("__INSTALL_ROOT__", ($Root -replace "\\", "\\"))
$cfg = $cfg.Replace("%LOCALAPPDATA%", ($env:LOCALAPPDATA -replace "\\", "\\"))
Set-Content $Config $cfg -Encoding UTF8
Write-Host "bridge_config.json patched for this machine"

# --- 3. Devin CLI ---------------------------------------------------------
$devinExe = Join-Path $env:LOCALAPPDATA "Programs\Devin\resources\app\extensions\windsurf\devin\bin\devin.exe"
if (Test-Path $devinExe) {
    Write-Host "Devin CLI found" -ForegroundColor Green
} else {
    Write-Host "WARNING: Devin not found at $devinExe" -ForegroundColor Yellow
    Write-Host "  Install the Devin app and run 'devin login' before autonomy works."
}

# --- 4. Companion venv + deps --------------------------------------------
if (-not $SkipCompanionDeps) {
    $compDir = Join-Path $Root "companion"
    $venvPy = Join-Path $compDir ".venv\Scripts\python.exe"
    if (-not (Test-Path $venvPy)) {
        Write-Host "Creating companion venv..."
        & cmd /c "$py -m venv `"$compDir\.venv`""
    }
    Write-Host "Installing companion deps (may take a while)..."
    & "$venvPy" -m pip install --quiet --upgrade pip
    & "$venvPy" -m pip install --quiet -r (Join-Path $compDir "companion_requirements.txt")
    & "$venvPy" -m pip install --quiet pillow numpy httpx opencv-python-headless
    Write-Host "Companion deps installed" -ForegroundColor Green
}

# --- 5. Autostart ----------------------------------------------------------
$startup = [Environment]::GetFolderPath("Startup")
$cmdPath = Join-Path $startup "DevinBridgeDaemon.cmd"
$watchdog = Join-Path $Bridge "daemon_watchdog.py"
$pyExe = (& cmd /c "$py -c `"import sys;print(sys.executable)`"").Trim()
$pywExe = $pyExe -replace "python\.exe$", "pythonw.exe"
if (-not (Test-Path $pywExe)) { $pywExe = $pyExe }
@"
@echo off
rem DevinBridge daemon autostart (auto-generated by setup.ps1)
start "" /min "$pywExe" "$watchdog"
"@ | Set-Content $cmdPath -Encoding ASCII
Write-Host "Startup registered: $cmdPath"

# --- 6. Done ---------------------------------------------------------------
Write-Host ""
Write-Host "== Setup complete ==" -ForegroundColor Cyan
Write-Host "Next steps:"
Write-Host "  1. devin login                                    (one-time auth)"
Write-Host "  2. python init_project.py --repo <path> --goal ""<goal>"""
Write-Host "  3. python -m DevinBridge.daemon                  (or reboot/logon)"
